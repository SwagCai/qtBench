def hilbert_series(points, n: int, *, spanning: str = "involution", max_weight: int, exact: bool = False):
    """``[dim R(X)_0, dim R(X)_1, ...]`` for the locus of the given points.

    The modular ranks are computed with both primes of ``PRIMES`` and must agree.
    This is the fast generation path; use ``certify_exact.py`` for the independent
    proof-enabled computation over the rational field.
    """
    points = list(points)
    if exact:
        return _hilbert_series_exact(points, n, spanning=spanning, max_weight=max_weight)
    series = [
        _hilbert_series_modular(points, n, spanning=spanning, max_weight=max_weight, prime=prime)
        for prime in PRIMES
    ]
    if series[0] != series[1]:
        raise RuntimeError(f"modular ranks disagree between primes: {series}")
    return series[0]


def iter_involution_images(n: int, a: int):
    """The images ``(pi(1), ..., pi(n))`` of every involution in ``M_{n,a}``.

    Kept here so the oracle is self-contained; the generator checks that this
    agrees with the public enumerator in ``qtbench.combinatorics``.
    """

    def walk(free: tuple[int, ...], fixed_left: int):
        if not 0 <= fixed_left <= len(free) or (len(free) - fixed_left) % 2:
            return
        if not free:
            yield ()
            return
        smallest, rest = free[0], free[1:]
        if fixed_left:
            for tail in walk(rest, fixed_left - 1):
                yield ((smallest, smallest), *tail)
        for index, partner in enumerate(rest):
            for tail in walk(rest[:index] + rest[index + 1:], fixed_left):
                yield ((smallest, partner), *tail)

    for cycles in walk(tuple(range(1, n + 1)), a):
        images = [0] * n
        for i, j in cycles:
            images[i - 1] = j
            images[j - 1] = i
        yield tuple(images)


def involution_hilbert_series(n: int, a: int, *, exact: bool = False):
    """``Hilb(R(M_{n,a}); q)`` as a coefficient list, index = degree in ``q``.

    A partial involution is contained in some member of ``M_{n,a}`` only if it has
    at most ``a`` fixed points and at most ``(n - a) / 2`` 2-cycles, so its weight
    is at most ``(n + a) / 2``; that bound is attained by the partial involutions
    that pin down a single point, which is why the spanning set of that weight
    already spans ``C[M_{n,a}]``.
    """
    if not 0 <= a <= n or (n - a) % 2:
        raise ValueError(
            f"M_{{{n},{a}}} is empty: need 0 <= a <= n and a congruent to n (mod 2)"
        )
    return hilbert_series(
        iter_involution_images(n, a),
        n,
        spanning="involution",
        max_weight=(n + a) // 2,
        exact=exact,
    )


def permutation_hilbert_series(n: int, *, exact: bool = False):
    """``Hilb(R(S_n); q)`` for the *full* permutation matrix locus.

    Used only to validate the machinery: Rhoades proved this equals
    ``sum_{w in S_n} q^{n - lis(w)}``, an answer the involution computation never
    sees.
    """
    return hilbert_series(
        permutations(range(1, n + 1)), n, spanning="permutation", max_weight=n, exact=exact
    )
